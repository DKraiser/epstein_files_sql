-- Upstream runs are distinct from this project's own import-run log.
CREATE TABLE IF NOT EXISTS provenance_runs (
    run_id TEXT PRIMARY KEY,                         -- 112 UUID-shaped and 11 non-UUID source IDs
    started_at_raw TEXT NOT NULL,
    started_at_parsed TIMESTAMPTZ,
    started_at_status SMALLINT NOT NULL REFERENCES enum_parse_statuses(status_id) ON DELETE RESTRICT,
    completed_at_raw TEXT NOT NULL,
    completed_at_parsed TIMESTAMPTZ,
    completed_at_local_parsed TIMESTAMP WITHOUT TIME ZONE,
    completed_at_status SMALLINT NOT NULL REFERENCES enum_parse_statuses(status_id) ON DELETE RESTRICT,
    run_status SMALLINT NOT NULL REFERENCES enum_run_statuses(status_id) ON DELETE RESTRICT,
    input_dir TEXT NOT NULL,
    output_name TEXT NOT NULL,
    model_raw TEXT NOT NULL,
    model_status SMALLINT NOT NULL REFERENCES enum_parse_statuses(status_id) ON DELETE RESTRICT,
    dpi INTEGER NOT NULL,
    workers INTEGER NOT NULL,
    rpm INTEGER NOT NULL,
    git_commit TEXT,
    hostname TEXT,
    total_files INTEGER NOT NULL,
    success_count INTEGER NOT NULL,
    fail_count INTEGER NOT NULL,
    input_tokens BIGINT NOT NULL,
    output_tokens BIGINT NOT NULL,
    cost_usd NUMERIC NOT NULL,
    last_heartbeat_raw TEXT,
    last_heartbeat_parsed TIMESTAMPTZ,
    last_heartbeat_status SMALLINT NOT NULL REFERENCES enum_parse_statuses(status_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS provenance_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file TEXT NOT NULL,
    source_row BIGINT NOT NULL CHECK (source_row >= 0),
    file_key TEXT NOT NULL,
    output_name TEXT NOT NULL,
    pdf_path TEXT NOT NULL,
    pdf_sha256_raw TEXT,
    pdf_sha256_parsed BYTEA CHECK (pdf_sha256_parsed IS NULL OR octet_length(pdf_sha256_parsed) = 32),
    pdf_sha256_status SMALLINT NOT NULL REFERENCES enum_parse_statuses(status_id) ON DELETE RESTRICT,
    pdf_size_bytes BIGINT,
    file_status SMALLINT NOT NULL REFERENCES enum_file_statuses(status_id) ON DELETE RESTRICT,
    output_path TEXT,
    output_sha256_raw TEXT,
    output_sha256_parsed BYTEA CHECK (output_sha256_parsed IS NULL OR octet_length(output_sha256_parsed) = 32),
    output_sha256_status SMALLINT NOT NULL REFERENCES enum_parse_statuses(status_id) ON DELETE RESTRICT,
    first_seen_at_raw TEXT NOT NULL,
    first_seen_at_parsed TIMESTAMPTZ,
    first_seen_at_status SMALLINT NOT NULL REFERENCES enum_parse_statuses(status_id) ON DELETE RESTRICT,
    processed_at_raw TEXT NOT NULL,
    processed_at_parsed TIMESTAMPTZ,
    processed_at_status SMALLINT NOT NULL REFERENCES enum_parse_statuses(status_id) ON DELETE RESTRICT,
    run_id TEXT REFERENCES provenance_runs(run_id) ON DELETE RESTRICT,
    document_id BIGINT REFERENCES documents(id) ON DELETE RESTRICT,
    document_match_status SMALLINT NOT NULL REFERENCES enum_match_statuses(status_id) ON DELETE RESTRICT,
    input_tokens BIGINT,
    output_tokens BIGINT,
    api_latency_ms BIGINT,
    attempts INTEGER NOT NULL,
    error_message TEXT,
    model_used_raw TEXT NOT NULL,
    model_used_status SMALLINT NOT NULL REFERENCES enum_parse_statuses(status_id) ON DELETE RESTRICT,
    validation_score SMALLINT,
    UNIQUE (source_file, source_row)
);

-- Preserve each source model token and its order while normalizing model names.
CREATE TABLE IF NOT EXISTS provenance_run_models (
    run_id TEXT NOT NULL REFERENCES provenance_runs(run_id) ON DELETE CASCADE,
    model_id SMALLINT NOT NULL REFERENCES enum_models(model_id) ON DELETE RESTRICT,
    PRIMARY KEY (run_id, model_id)
);
CREATE TABLE IF NOT EXISTS provenance_file_models (
    file_id BIGINT NOT NULL REFERENCES provenance_files(id) ON DELETE CASCADE,
    model_id SMALLINT NOT NULL REFERENCES enum_models(model_id) ON DELETE RESTRICT,
    PRIMARY KEY (file_id, model_id)
);
